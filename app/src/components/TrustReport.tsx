import React from 'react';
import {
  Shield,
  Eye,
  Brain,
  HelpCircle,
  AlertTriangle,
  CheckCircle,
  Clock,
  FileText,
  ArrowLeft,
  Download,
  Printer,
} from 'lucide-react';
import { Assessment } from '../types/assessment';
import { formatEnum, formatReviewTrigger } from '../utils/formatters';

interface TrustReportProps {
  assessment: Assessment;
  onBack: () => void;
}

export default function TrustReport({ assessment, onBack }: TrustReportProps) {
  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="max-w-4xl mx-auto space-y-6">
      {/* Header */}
      <div className="flex flex-col sm:flex-row justify-between items-start sm:items-center gap-4 print:hidden">
        <div className="flex items-center gap-3">
          <button
            onClick={onBack}
            className="p-2 hover:bg-gray-100 rounded-lg transition-colors"
          >
            <ArrowLeft className="w-5 h-5 text-gray-600" />
          </button>
          <div>
            <h2 className="text-xl font-bold text-gray-900">Trust Report</h2>
            <p className="text-xs text-gray-500">{assessment.assessment_id}</p>
          </div>
        </div>
        <div className="flex items-center gap-2">
          <button
            onClick={handlePrint}
            className="inline-flex items-center gap-2 px-3 py-2 bg-white border border-gray-300 text-gray-700 rounded-lg text-sm font-medium hover:bg-gray-50 transition-colors"
          >
            <Printer className="w-4 h-4" />
            Print
          </button>
        </div>
      </div>

      {/* Report Document */}
      <div className="bg-white rounded-xl border border-gray-200 shadow-sm overflow-hidden print:border-0 print:shadow-none">
        {/* Report Header */}
        <div className="bg-gradient-to-r from-emerald-600 to-teal-700 px-8 py-6 text-white">
          <div className="flex items-center gap-3 mb-4">
            <Shield className="w-8 h-8" />
            <div>
              <h1 className="text-xl font-bold">Scrap Evidence Trust Report</h1>
              <p className="text-emerald-100 text-sm">AI-Assisted Visual Assessment</p>
            </div>
          </div>
          <div className="grid grid-cols-2 sm:grid-cols-4 gap-4 text-sm">
            <div>
              <p className="text-emerald-200 text-xs">Assessment ID</p>
              <p className="font-mono font-medium">{assessment.assessment_id}</p>
            </div>
            <div>
              <p className="text-emerald-200 text-xs">Created</p>
              <p className="font-medium">{new Date(assessment.created_at).toLocaleString()}</p>
            </div>
            <div>
              <p className="text-emerald-200 text-xs">Status</p>
              <p className="font-medium capitalize">{assessment.status.replace('_', ' ')}</p>
            </div>
            <div>
              <p className="text-emerald-200 text-xs">Confidence</p>
              <p className="font-medium">{Math.round(assessment.confidence * 100)}%</p>
            </div>
          </div>
        </div>

        <div className="px-8 py-6 space-y-6">
          {/* Disclaimer */}
          <div className="p-4 bg-amber-50 border border-amber-200 rounded-lg">
            <div className="flex items-start gap-2">
              <AlertTriangle className="w-4 h-4 text-amber-600 flex-shrink-0 mt-0.5" />
              <div>
                <p className="text-sm font-semibold text-amber-900">Important Limitations</p>
                <p className="text-xs text-amber-800 mt-1">
                  This report is generated by AI visual analysis of photographs. It is a preliminary assessment only.
                  The system <strong>cannot</strong> determine exact chemical composition, alloy grade, purity, weight,
                  or market value from images alone. All findings require physical verification before commercial decisions.
                </p>
              </div>
            </div>
          </div>

          {/* Verification Status */}
          <div className="flex items-start gap-3 p-4 bg-gray-50 rounded-lg">
            {assessment.human_review_required ? (
              <>
                <AlertTriangle className="w-6 h-6 text-amber-500 flex-shrink-0 mt-0.5" />
                <div>
                  <p className="text-sm font-semibold text-gray-900">Not Verified — Requires Human Review</p>
                  <p className="text-xs text-gray-600">This assessment has not been reviewed by a human expert.</p>
                  {assessment.human_review_reasons && assessment.human_review_reasons.length > 0 && (
                    <div className="flex flex-wrap gap-1.5 mt-2">
                      {assessment.human_review_reasons.map((reason, idx) => (
                        <span
                          key={idx}
                          className="inline-flex items-center px-2 py-0.5 bg-amber-100 text-amber-800 rounded text-xs font-medium"
                        >
                          {formatReviewTrigger(reason)}
                        </span>
                      ))}
                    </div>
                  )}
                </div>
              </>
            ) : (
              <>
                <Clock className="w-6 h-6 text-blue-500 flex-shrink-0 mt-0.5" />
                <div>
                  <p className="text-sm font-semibold text-gray-900">AI-Generated — Pending Verification</p>
                  <p className="text-xs text-gray-600">This assessment is AI-generated and has not been independently verified.</p>
                </div>
              </>
            )}
          </div>

          {/* Evidence Summary */}
          <section>
            <h3 className="text-base font-semibold text-gray-900 mb-3 flex items-center gap-2">
              <FileText className="w-4 h-4 text-gray-500" />
              Evidence Summary
            </h3>
            <div className="grid grid-cols-2 gap-3">
              <div className="p-3 bg-gray-50 rounded-lg">
                <p className="text-xs text-gray-500">Evidence Quality</p>
                <p className="text-sm font-medium text-gray-900 capitalize">
                  {assessment.evidence_quality.status.replace('_', ' ')}
                </p>
              </div>
              <div className="p-3 bg-gray-50 rounded-lg">
                <p className="text-xs text-gray-500">Quality Score</p>
                <p className="text-sm font-medium text-gray-900">{assessment.evidence_quality.overall_score}/100</p>
              </div>
              <div className="p-3 bg-gray-50 rounded-lg">
                <p className="text-xs text-gray-500">Images Analyzed</p>
                <p className="text-sm font-medium text-gray-900">{assessment.processing_metadata.image_count}</p>
              </div>
              <div className="p-3 bg-gray-50 rounded-lg">
                <p className="text-xs text-gray-500">XRF Recommended</p>
                <p className="text-sm font-medium text-gray-900">{assessment.scanner_xrf_recommended ? 'Yes' : 'No'}</p>
              </div>
            </div>
          </section>

          {/* Findings by Category */}
          <section>
            <h3 className="text-base font-semibold text-gray-900 mb-3 flex items-center gap-2">
              <Eye className="w-4 h-4 text-blue-500" />
              Observed — Directly Visible
            </h3>
            <div className="space-y-2">
              {assessment.observed.map((obs, idx) => (
                <div key={idx} className="p-3 bg-blue-50 border-l-4 border-blue-400 rounded-r-lg">
                  <p className="text-sm text-gray-900">{obs.finding}</p>
                  <p className="text-xs text-gray-500 mt-1">Evidence: {obs.supporting_evidence}</p>
                </div>
              ))}
              {assessment.observed.length === 0 && (
                <p className="text-sm text-gray-500 italic p-3">No direct observations recorded.</p>
              )}
            </div>
          </section>

          <section>
            <h3 className="text-base font-semibold text-gray-900 mb-3 flex items-center gap-2">
              <Brain className="w-4 h-4 text-amber-500" />
              Inferred — Tentative Interpretations
            </h3>
            <div className="space-y-2">
              {assessment.inferred.map((inf, idx) => (
                <div key={idx} className="p-3 bg-amber-50 border-l-4 border-amber-400 rounded-r-lg">
                  <div className="flex items-start justify-between gap-2">
                    <p className="text-sm text-gray-900">{inf.finding}</p>
                    <span className="text-xs font-bold text-amber-700 bg-amber-100 px-2 py-0.5 rounded">
                      {Math.round(inf.confidence * 100)}%
                    </span>
                  </div>
                  <p className="text-xs text-gray-500 mt-1">Limitations: {inf.limitations}</p>
                </div>
              ))}
              {assessment.inferred.length === 0 && (
                <p className="text-sm text-gray-500 italic p-3">No inferences recorded.</p>
              )}
            </div>
          </section>

          <section>
            <h3 className="text-base font-semibold text-gray-900 mb-3 flex items-center gap-2">
              <HelpCircle className="w-4 h-4 text-red-500" />
              Unknown — Cannot Be Determined
            </h3>
            <div className="space-y-2">
              {assessment.unknown.map((unk, idx) => (
                <div key={idx} className="p-3 bg-red-50 border-l-4 border-red-400 rounded-r-lg">
                  <p className="text-sm text-gray-900">{unk.item}</p>
                  <p className="text-xs text-gray-500 mt-1">Required: {unk.required_evidence}</p>
                </div>
              ))}
              {assessment.unknown.length === 0 && (
                <p className="text-sm text-gray-500 italic p-3">No unknowns recorded.</p>
              )}
            </div>
          </section>

          {/* Proposed Assessment */}
          {assessment.proposed_assessment && (
            <section>
              <h3 className="text-base font-semibold text-gray-900 mb-3">Proposed Assessment (Unverified)</h3>
              <div className="p-4 bg-gray-50 rounded-lg">
                <p className="text-sm text-gray-700 mb-3">{assessment.proposed_assessment.description}</p>
                <div className="grid grid-cols-2 gap-2 mb-3">
                  <div>
                    <span className="text-xs text-gray-500">Material Family:</span>
                    <span className="text-sm font-medium ml-1 text-gray-900">
                      {formatEnum(assessment.proposed_assessment.material_family)}
                    </span>
                  </div>
                  <div>
                    <span className="text-xs text-gray-500">Scrap Form:</span>
                    <span className="text-sm font-medium ml-1 text-gray-900">
                      {formatEnum(assessment.proposed_assessment.scrap_form)}
                    </span>
                  </div>
                </div>
                {assessment.proposed_assessment.caveats.length > 0 && (
                  <div className="mt-3 pt-3 border-t border-gray-200">
                    <p className="text-xs font-medium text-gray-700 mb-1">Caveats:</p>
                    <ul className="space-y-0.5">
                      {assessment.proposed_assessment.caveats.map((c, i) => (
                        <li key={i} className="text-xs text-gray-600">• {c}</li>
                      ))}
                    </ul>
                  </div>
                )}
              </div>
            </section>
          )}

          {/* Recommendations */}
          {assessment.recommended_next_steps.length > 0 && (
            <section>
              <h3 className="text-base font-semibold text-gray-900 mb-3">Recommended Next Steps</h3>
              <ol className="space-y-2">
                {assessment.recommended_next_steps.map((step, idx) => (
                  <li key={idx} className="flex items-start gap-2 text-sm text-gray-700">
                    <span className="w-5 h-5 bg-emerald-100 text-emerald-700 rounded-full flex items-center justify-center text-xs font-bold flex-shrink-0">
                      {idx + 1}
                    </span>
                    {step}
                  </li>
                ))}
              </ol>
            </section>
          )}

          {/* Footer */}
          <div className="pt-4 border-t border-gray-200">
            <div className="flex flex-col sm:flex-row justify-between items-start sm:items-center gap-2 text-xs text-gray-500">
              <div>
                <p>Generated by ScrapTrust Assessment System v1.0 (MVP)</p>
                <p className="mt-0.5">Model: {assessment.processing_metadata.model_used} • Processing time: {assessment.processing_metadata.processing_time_ms}ms</p>
              </div>
              <div className="text-right">
                <p>This report is not a substitute for professional material testing.</p>
                <p>All findings require independent verification.</p>
              </div>
            </div>
          </div>
        </div>
      </div>
    </div>
  );
}


